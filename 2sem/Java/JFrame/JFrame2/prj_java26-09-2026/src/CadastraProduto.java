    private void btnSalvaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvaActionPerformed
        // TODO add your handling code here:
        String id = txtID.getText();
        String nome = txtNome.getText();
        float valor = Float.parseFloat(txtVal.getText());
        int estoque = Integer.parseInt(txtEst.getText());
        
        if (valor > 0.0 && estoque >= 0){
            DefaultTableModel produtos = (DefaultTableModel) tblProdutos.getModel();

            Object[] novoProduto = new Object[]{
                id, nome, valor, estoque
            };

            produtos.addRow(novoProduto);

            // Limpando campos
            Limpar();
        } else{
            
            if (valor <= 0.0){ JOptionPane.showMessageDialog(this, "Valor incorreto. Tente novamente."); }
            if (estoque < 0) { JOptionPane.showMessageDialog(this, "Estoque negativo. Tente novamente."); }
        }
    }//GEN-LAST:event_btnSalvaActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        // TODO add your handling code here:
        int linha = tblProdutos.getSelectedRow();
        
        
        
        if (linha == -1){
            JOptionPane.showMessageDialog(this, "Por favor, selecione uma linha.");
        } else{
            DefaultTableModel produtos = (DefaultTableModel) tblProdutos.getModel();
            produtos.removeRow(linha);
            
            JOptionPane.showMessageDialog(this, "Produto removido.");
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    /**
     * @param args the command line arguments
     */
    
    public void Limpar(){
        txtID.setText("");
        txtNome.setText("");
        txtVal.setText("");
        txtEst.setText("");
    }
    
